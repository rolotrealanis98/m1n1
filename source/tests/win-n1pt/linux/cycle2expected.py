"""tests/win-n1pt: Linux's phase-1 port cycle (capture cap2 pcie-cycle.txt, this machine) -> the expected write list
the resident's PORT_CYCLE is compared with (test_plat "cycle == Linux capture").

Window: from `enter reset_root_port` to the LTSSM start write in port_train (link-up wait, the 100 ms settle and the
later pci_restore_state are compared separately / not register writes of the cycle).
Output lines: `<kind> <region> <offset> <mask> <value> <seq> <label>`
  kind  W      a write whose bits under mask must equal value
        T      a write to that register must happen (Linux wrote back the value it read: no bit changed)
        X      an ADT tunable write (apple,*-tunables lists; m1n1 applies the same ADT lists through
               tunables_apply_local_addr, which the host model does not expand): not compared write-for-write
  region port | lane | i2axi | rp (root port config / DBI) | perst (the PERST# pad: 0x202 asserted, 0x203 released)
Usage: cycle2expected.py pcie-cycle.txt > linux-cycle.expected
       cycle2expected.py pcie-cycle.txt cold > linux-cold-port.expected
  cold: Linux's cold_train port part instead (first `enter port_enable` .. LTSSM start), compared with the resident's
        PREP training (the shared-PHY part before it, in unresolved `?` addresses, is not compared: m1n1's stages A/S)
"""
import re
import sys

REG = {'port': 'port', 'phylane': 'lane', 'intr2axi': 'i2axi', 'dbi': 'rp', 'pcicfg': 'rp'}
TUNABLE_PORT = {0x140, 0x144, 0x8a8, 0x8ac}


def main(path, mode='cycle'):
    lines = open(path).read().splitlines()
    out, on, last_rd, prev_rd = [], False, {}, None
    for ln in lines:
        f = ln.split(None, 4)
        if len(f) < 5:
            continue
        seq, label, rest = f[0], f[3], f[4]
        if 'MARK' in rest and ((mode == 'cycle' and 'enter reset_root_port' in rest) or
                               (mode == 'cold' and 'enter port_enable' in rest)):
            on = True
            continue
        if not on:
            continue
        m = re.match(r'RD\s+(\w+)\+0x([0-9a-f]+)(?: \((\d)B\))? = 0x([0-9a-f]+)', rest)
        if m:
            prev_rd = (m.group(1), int(m.group(2), 16), int(m.group(4), 16))  # a WR right after it is a live RMW
            continue
        rd, prev_rd = prev_rd, None
        m = re.match(r'CFGRD rootport cfg\+0x([0-9a-f]+) = 0x([0-9a-f]+)', rest)
        if m:
            last_rd[('rootport', int(m.group(1), 16))] = int(m.group(2), 16)
            continue
        m = re.match(r'GPIO\s+PERST# logical level (\d)', rest)
        if m:
            out.append(('W', 'perst', 0, 0x27f, 0x202 if m.group(1) == '1' else 0x203, seq, label))
            continue
        m = re.match(r'CFGWR rootport cfg\+0x([0-9a-f]+)(?: \((\d)B\))? = 0x([0-9a-f]+)', rest)
        if m:
            off, size, v = int(m.group(1), 16), int(m.group(2) or 4), int(m.group(3), 16)
            mask = ((1 << (8 * size)) - 1) << (8 * (off & 3))
            out.append(('W', 'rp', off & ~3, mask, (v << (8 * (off & 3))) & mask, seq, label))
            continue
        m = re.match(r'WR\s+(\w+)\+0x([0-9a-f]+)(?: \((\d)B\))? = 0x([0-9a-f]+)(?:\s+\(rmw: clear 0x([0-9a-f]+) set 0x([0-9a-f]+)\))?', rest)
        if not m:
            continue
        region, off, size, v = REG[m.group(1)], int(m.group(2), 16), int(m.group(3) or 4), int(m.group(4), 16)
        sh = 8 * (off & 3)
        if m.group(5) is not None:
            clear, sset = int(m.group(5), 16), int(m.group(6), 16)
            tunable = (label == 'port_enable/rmw' and region == 'port' and off in TUNABLE_PORT) or \
                      label == 'port_configure/rmw'
            out.append(('X' if tunable else 'W', region, off & ~3, (clear | sset) << sh, sset << sh, seq, label))
        else:
            mask = ((1 << (8 * size)) - 1) << sh
            if rd is not None and rd[:2] == (m.group(1), off) and size == 4:
                changed = rd[2] ^ v
                out.append(('W' if changed else 'T', region, off & ~3, changed, v & changed, seq, label))
            else:
                out.append(('W', region, off & ~3, mask, (v << sh) & mask, seq, label))
        if region == 'port' and off == 0x80 and label == 'port_train/rmw':
            break  # LTSSM start: end of the compared window
    print(f'# generated by cycle2expected.py ({mode}) from capture cap2 pcie-cycle.txt (Linux on this machine)')
    for k, r, o, mk, v, s, lb in out:
        print(f'{k} {r} 0x{o:03x} 0x{mk:08x} 0x{v:08x} {s} {lb}')


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2] if len(sys.argv) > 2 else 'cycle')
